export type MessageKey = keyof typeof ARABIC;
export type MessageValues = Record<string, string | number>;

/** Marks a message that is shown later, for example an error thrown in a worker. The compiler checks it has a translation. */
export const msg = (key: MessageKey): MessageKey => key;

/** Text from outside the app, like a message from OpenSCAD, has no translation and stays as it is. */
export function translate(language: Language, key: string, values?: MessageValues): string {
  const text = language === 'ar' ? ((ARABIC as Record<string, string>)[key] ?? key) : key;
  return values ? text.replace(/\{(\w+)\}/g, (whole, name) => (name in values ? String(values[name]) : whole)) : text;
}

export const arabicMessages = (): readonly (readonly [string, string])[] => Object.entries(ARABIC);
